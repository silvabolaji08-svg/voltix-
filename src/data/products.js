/* ---------------------------------------------------------------- helpers */

export const getProductBySlug = (slug) => products.find((p) => p.slug === slug)
export const getProductById = (id) => products.find((p) => p.id === id)

export const getCategory = (id) => categories.find((c) => c.id === id)

export const featuredProducts = () => products.filter((p) => p.tags.includes('bestseller')).slice(0, 4)
export const newArrivals = () => products.filter((p) => p.tags.includes('new')).slice(0, 4)
export const onSale = () => products.filter((p) => p.compareAt)

export const relatedProducts = (product, limit = 4) =>
  products.filter((p) => p.category === product.category && p.id !== product.id).slice(0, limit)

export const priceBounds = () => {
  const values = products.map((p) => p.price)
  return { min: Math.floor(Math.min(...values)), max: Math.ceil(Math.max(...values)) }
}

